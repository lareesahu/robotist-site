def roster(base):
    page = urllib.request.urlopen(
        urllib.request.Request(base.rstrip('/') + '/grn/', headers={'User-Agent': 'Mozilla/5.0'}),
        timeout=45).read().decode('utf-8', 'replace')
    people = []
    for art in re.findall(r'<article class="member">(.*?)</article>', page, re.S):
        name = re.search(r'<h3>(.*?)</h3>', art, re.S)
        loc = re.search(r'class="member-loc">(.*?)<', art, re.S)
        photo = re.search(r'<img src="([^"]+)"', art)
        mono = re.search(r'<span>([A-Z][A-Za-z]{0,3})</span>', art)
        if not name:
            continue
        people.append({
            'name': re.sub(r'\s+', ' ', name.group(1)).strip(),
            'location': re.sub(r'\s+', ' ', loc.group(1)).strip() if loc else '',
            'photo': photo.group(1) if photo else '',
            'monogram': mono.group(1) if mono else '',
        })
    return people


def block(people, variant=''):
    faces = []
    for p in people:
        face = (f'<img src="{html.escape(p["photo"])}" alt="{html.escape(p["name"])}" loading="lazy" decoding="async">'
                if p['photo'] else f'<i>{html.escape(p["monogram"] or p["name"][:2].upper())}</i>')
        faces.append(
            f'<li class="grn-person">'
            f'<span class="grn-face">{face}</span>'
            f'<span><span class="grn-name">{html.escape(p["name"])}</span>'
            f'<span class="grn-loc">{html.escape(p["location"])}</span></span>'
            f'</li>')
    cls = 'grn-strip' + (' grn-strip--about' if variant == 'about' else '')
    return (
        f'{START}\n'
        f'<div class="{cls}">\n'
        f'  <div class="grn-strip-head">\n'
        f'    <div><p class="grn-eyebrow">Global Robotists Network</p>'
        f'<p class="grn-lede">Engineers and integrators we bring in on agreed terms, city by city. '
        f'Every profile is published with the member\'s written approval.</p></div>\n'
        f'    <a class="grn-link" href="/grn/">Meet the network ↗</a>\n'
        f'  </div>\n'
        f'  <ul class="grn-people">\n    ' + '\n    '.join(faces) + f'\n  </ul>\n'
        f'</div>\n{END}')


def inject(page_path, variant):
    src = page_path.read_text(encoding='utf-8')
    if '/* Global Robotists Network strip' not in src:
        src = src.replace('</style>', CSS + '</style>', 1)

    if START in src:
        start = src.index(START)
        end = src.index(END) + len(END)
        src = src[:start] + f'@@GRN@@' + src[end:]
    else:
        anchor = src.find('<div class="leadership-grid">')
        if anchor < 0:
            raise SystemExit(f'no leadership grid in {page_path}')
        depth = 0
        close = None
        for m in re.finditer(r'<div\b|</div>', src[anchor:]):
            depth += -1 if m.group(0) == '</div>' else 1
            if depth == 0:
                close = anchor + m.end()
                break
        if close is None:
            raise SystemExit(f'unbalanced grid in {page_path}')
        src = src[:close] + '\n@@GRN@@' + src[close:]

